CREATE SEQUENCE purchase_number_seq START WITH 5001 INCREMENT BY 1;

CREATE TABLE cash_shifts (
    id UUID PRIMARY KEY,
    shift_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    currency CHAR(3) NOT NULL,
    opening_cash NUMERIC(14,2) NOT NULL CHECK (opening_cash >= 0),
    expected_cash NUMERIC(14,2) NOT NULL DEFAULT 0,
    counted_cash NUMERIC(14,2),
    variance NUMERIC(14,2),
    opened_by VARCHAR(80) NOT NULL,
    closed_by VARCHAR(80),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    CONSTRAINT ck_cash_shift_close_state CHECK (
      (status = 'OPEN' AND closed_at IS NULL AND counted_cash IS NULL AND closed_by IS NULL)
      OR
      (status = 'CLOSED' AND closed_at IS NOT NULL AND counted_cash IS NOT NULL AND closed_by IS NOT NULL)
    )
);
CREATE UNIQUE INDEX uq_cash_shift_single_open ON cash_shifts(status) WHERE status = 'OPEN';
CREATE INDEX ix_cash_shifts_opened_at ON cash_shifts(opened_at DESC);

CREATE TABLE cash_movements (
    id UUID PRIMARY KEY,
    shift_id UUID NOT NULL REFERENCES cash_shifts(id) ON DELETE RESTRICT,
    movement_type VARCHAR(24) NOT NULL CHECK (
      movement_type IN ('OPENING', 'SALE', 'REFUND', 'CASH_IN', 'CASH_OUT', 'EXPENSE', 'PURCHASE')
    ),
    direction VARCHAR(3) NOT NULL CHECK (direction IN ('IN', 'OUT')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    reference_type VARCHAR(32),
    reference_id UUID,
    description VARCHAR(240),
    actor VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_cash_movements_shift ON cash_movements(shift_id, created_at, id);
ALTER TABLE payments
    ADD COLUMN cash_shift_id UUID REFERENCES cash_shifts(id) ON DELETE RESTRICT;

CREATE TABLE expenses (
    id UUID PRIMARY KEY,
    category VARCHAR(80) NOT NULL,
    description VARCHAR(240) NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL,
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('CASH', 'WALLET', 'BANK_CARD')),
    cash_shift_id UUID REFERENCES cash_shifts(id) ON DELETE RESTRICT,
    incurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_expense_cash_shift CHECK (payment_method <> 'CASH' OR cash_shift_id IS NOT NULL)
);
CREATE INDEX ix_expenses_incurred_at ON expenses(incurred_at DESC);
CREATE INDEX ix_expenses_category ON expenses(category, incurred_at DESC);

CREATE TABLE suppliers (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone VARCHAR(32),
    email VARCHAR(160),
    notes VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_suppliers_active_name ON suppliers(active, name);

CREATE TABLE purchases (
    id UUID PRIMARY KEY,
    purchase_no BIGINT NOT NULL DEFAULT nextval('purchase_number_seq') UNIQUE,
    supplier_id UUID REFERENCES suppliers(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'POSTED' CHECK (status IN ('POSTED', 'VOIDED')),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    paid_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    due_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (due_amount >= 0),
    currency CHAR(3) NOT NULL,
    payment_method VARCHAR(20) CHECK (payment_method IN ('CASH', 'WALLET', 'BANK_CARD')),
    cash_shift_id UUID REFERENCES cash_shifts(id) ON DELETE RESTRICT,
    purchased_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_purchase_amounts CHECK (
      total = subtotal - discount_amount
      AND total = paid_amount + due_amount
      AND discount_amount <= subtotal
    ),
    CONSTRAINT ck_purchase_cash_shift CHECK (
      paid_amount = 0 OR payment_method <> 'CASH' OR cash_shift_id IS NOT NULL
    )
);
CREATE INDEX ix_purchases_purchased_at ON purchases(purchased_at DESC);
CREATE INDEX ix_purchases_supplier ON purchases(supplier_id, purchased_at DESC);

CREATE TABLE purchase_lines (
    id UUID PRIMARY KEY,
    purchase_id UUID NOT NULL REFERENCES purchases(id) ON DELETE RESTRICT,
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    product_no_snapshot BIGINT NOT NULL,
    product_name_snapshot VARCHAR(120) NOT NULL,
    unit_snapshot VARCHAR(24) NOT NULL,
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(14,2) NOT NULL CHECK (unit_cost > 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total > 0)
);
CREATE INDEX ix_purchase_lines_purchase ON purchase_lines(purchase_id);

CREATE TABLE inventory_balances (
    product_id UUID PRIMARY KEY REFERENCES products(id) ON DELETE RESTRICT,
    quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    minimum_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (minimum_quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO inventory_balances(product_id)
SELECT id FROM products WHERE stock_tracked = TRUE
ON CONFLICT (product_id) DO NOTHING;

CREATE TABLE inventory_movements (
    id UUID PRIMARY KEY,
    product_id UUID NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    movement_type VARCHAR(24) NOT NULL CHECK (
      movement_type IN ('PURCHASE', 'SALE', 'CANCEL_RETURN', 'RECEIPT', 'CONSUMPTION', 'WASTE', 'ADJUSTMENT')
    ),
    quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
    reference_type VARCHAR(32),
    reference_id UUID,
    reason VARCHAR(240),
    created_by VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_inventory_movements_product ON inventory_movements(product_id, created_at DESC);
CREATE INDEX ix_inventory_movements_reference ON inventory_movements(reference_type, reference_id);
